package compose

import (
	"fmt"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

type Compose struct {
	Services map[string]Service `yaml:"services"`
	Networks map[string]Network `yaml:"networks,omitempty"`
}

type Network struct {
	External bool `yaml:"external"`
}

type Service struct {
	Image         string            `yaml:"image"`
	ContainerName string            `yaml:"container_name"`
	Restart       string            `yaml:"restart"`
	EnvFile       []string          `yaml:"env_file,omitempty"`
	Ports         []string          `yaml:"ports,omitempty"`
	Volumes       []string          `yaml:"volumes,omitempty"`
	Networks      []string          `yaml:"networks,omitempty"`
	Labels        []string          `yaml:"labels,omitempty"`
	Environment   map[string]string `yaml:"environment,omitempty"`
	Healthcheck   *Healthcheck      `yaml:"healthcheck,omitempty"`
}

// Healthcheck mirrors the Compose healthcheck block.
type Healthcheck struct {
	Test        []string `yaml:"test"`
	Interval    string   `yaml:"interval,omitempty"`
	Timeout     string   `yaml:"timeout,omitempty"`
	Retries     int      `yaml:"retries,omitempty"`
	StartPeriod string   `yaml:"start_period,omitempty"`
}

// Spec describes a single-service compose file.
type Spec struct {
	ServiceName string
	Image       string
	Mode        string // local | traefik
	Network     string
	Ports       []string
	Volumes     []string
	EnvFiles    []string
	Traefik     TraefikOptions
	Healthcheck *Healthcheck
}

// Build turns a spec into a Compose document. It performs no I/O.
func Build(s Spec) (Compose, error) {
	service := Service{
		Image:         s.Image,
		ContainerName: s.ServiceName,
		Restart:       "unless-stopped",
		EnvFile:       s.EnvFiles,
		Volumes:       s.Volumes,
		Healthcheck:   s.Healthcheck,
	}

	c := Compose{Services: map[string]Service{}}

	switch s.Mode {
	case "traefik":
		net := s.Network
		if net == "" {
			net = "edge"
		}
		t := s.Traefik
		if t.Router == "" {
			t.Router = s.ServiceName
		}
		service.Networks = []string{net}
		service.Labels = BuildTraefikLabelsWith(t)
		c.Networks = map[string]Network{net: {External: true}}

	case "local", "":
		// Local mode publishes ports directly; --network is intentionally
		// ignored here, matching the original behaviour.
		service.Ports = s.Ports

	default:
		return Compose{}, fmt.Errorf("unknown mode %q", s.Mode)
	}

	c.Services[s.ServiceName] = service
	return c, nil
}

// Marshal renders a spec to YAML.
func Marshal(s Spec) ([]byte, error) {
	c, err := Build(s)
	if err != nil {
		return nil, err
	}
	return yaml.Marshal(c)
}

// Generate writes <path>/<service>/docker-compose.yml. Kept for backwards
// compatibility with the original positional API.
func Generate(
	path string,
	serviceName string,
	image string,
	mode string,
	domain string,
	network string,
	internalPort string,
	ports []string,
	volumes []string,
) error {
	data, err := Marshal(Spec{
		ServiceName: serviceName,
		Image:       image,
		Mode:        mode,
		Network:     network,
		Ports:       ports,
		Volumes:     volumes,
		Traefik:     TraefikOptions{Domain: domain, InternalPort: internalPort},
	})
	if err != nil {
		return err
	}
	dir := filepath.Join(path, serviceName)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "docker-compose.yml"), data, 0644)
}

// Parse reads a compose file generated by shipyard.
func Parse(file string) (*Compose, error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return nil, err
	}
	var c Compose
	if err := yaml.Unmarshal(data, &c); err != nil {
		return nil, err
	}
	return &c, nil
}
